export const ACTION_CASES = [...WALLET_ACTION_CASES, ...DEPOSIT_ACTION_CASES];

export function matrixInput(
  domain: AuditInput['domain'],
  actionName: string,
  overrides: Partial<AuditInput> = {},
): AuditInput {
  const actionCase = ACTION_CASES.find(
    ({ domain: candidateDomain, action }) => candidateDomain === domain && action === actionName,
  );
  assert.ok(actionCase, `${domain}/${actionName} fixture must exist`);
  return settingsInput({
    ...actionCase,
    ...actor(actionCase.actors[0] ?? 'ADMIN'),
    id: uuid7(),
    eventKey: `coverage:${auditSequence}`,
    ...overrides,
  });
}
